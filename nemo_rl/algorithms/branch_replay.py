# Branch replay: online selection of the turn a rollout is restarted from.
#
# A normal rollout (started from the task) is screened as soon as the critic has scored it in a training step.
# The branch turn is the turn whose critic value moved most while the model was writing it (last token of the turn
# minus its first token), in the direction of the rollout's outcome: the largest rise of a solved rollout (where it
# found its way), the largest drop of an unsolved one (where it went wrong).  A rollout that ran into the context
# limit is screened too, as unsolved.  The next time the task comes up in the training list, the rollout is
# restarted from the start of that turn: the turns before it are replayed verbatim and only the turns from the
# branch turn on are generated by the current policy and trained on.
#
# Nothing here waits for an epoch to finish.  The two data-driven thresholds are taken from a trailing window of the
# most recent normal rollouts (one epoch's worth by default), updated every training step:
#   - move threshold: a percentile of |move| over all candidate-position turns in the window;
#   - value band: the values v with v(1-v) >= the mean of p(1-p) at the root over the window.  With v the critic
#     value when the branch turn starts, a rise must start at or below the band's upper edge (not from a state that
#     was already nearly certain to succeed) and a drop at or above its lower edge; the other side is open, so a
#     drop from a high value and a rise from a low one are both eligible.
#
# This module is torch-free so that it can be checked offline against dumped rollouts.

from __future__ import annotations

import json
import os
import re
from collections import Counter, deque
from dataclasses import asdict, dataclass, field
from typing import Any, Optional

import numpy as np


@dataclass
class BranchReplayConfig:
    enabled: bool = False
    # Percentile (0-100) of |inside-turn move| over the window's candidate-position turns.
    move_percentile: float = 99.0
    # Turns later than this fraction of the rollout are not candidates.
    max_position: float = 0.8
    # Trailing window, in normal rollouts (rows of one pass over the task list by default).
    window_rollouts: int = 701
    # No selection until the window holds this many rollouts.
    min_window_rollouts: int = 256
    # "all": branch points from solved and unsolved rollouts; "solved": only from solved ones.
    source: str = "all"
    # First version: a rollout with a subagent session or a context compaction is not replayed.
    skip_subagent_or_compaction: bool = True
    # Directory shared with the Gym model server (its vllm_model.branch_replay_dir); NEMO_GYM_BRANCH_REPLAY_DIR
    # is the fallback.
    dir: Optional[str] = None


@dataclass
class RolloutTurns:
    """What the screen needs from one normal rollout (root trace only)."""

    task: str
    rollout_id: str
    step: int
    solved: bool  # False for a rollout that hit the context limit, whatever its tests say: its reward is 0
    first: np.ndarray  # critic value at the first generated token of each turn
    last: np.ndarray  # critic value at the last generated token of each turn
    root_mean: float  # mean critic value over the root turn's tokens
    has_subagent_or_compaction: bool = False
    truncated: bool = False


@dataclass
class BranchPoint:
    task: str
    rollout_id: str
    step: int
    solved: bool
    turns: int
    branch_turn: int  # 0-based index of the first turn the replay generates
    value_before: float
    move: float
    position: float
    truncated: bool = False


def _signal(p: float) -> float:
    p = min(max(float(p), 0.0), 1.0)
    return p * (1.0 - p)


@dataclass
class _WindowEntry:
    moves: np.ndarray
    root_signal: float


class BranchSelector:
    """Trailing-window thresholds, per-rollout screening and the per-task store of pending branch points."""

    def __init__(self, config: BranchReplayConfig):
        if config.source not in ("all", "solved"):
            raise ValueError(f"branch_replay.source must be 'all' or 'solved', got {config.source!r}")
        if not 0.0 < config.move_percentile < 100.0:
            raise ValueError("branch_replay.move_percentile must be in (0, 100)")
        self.config = config
        self._window: deque[_WindowEntry] = deque(maxlen=config.window_rollouts)
        self.pending: dict[str, BranchPoint] = {}
        self._step_reasons: Counter = Counter()
        self._step_selected: list[BranchPoint] = []
        self._step_screened = 0

    # -- thresholds -------------------------------------------------------------------------------------------
    def thresholds(self) -> Optional[tuple[float, float]]:
        """(move threshold, signal floor) from the window, or None while the window is too small."""
        if len(self._window) < self.config.min_window_rollouts:
            return None
        moves = [e.moves for e in self._window if e.moves.size]
        if not moves:
            return None
        move_threshold = float(np.percentile(np.concatenate(moves), self.config.move_percentile))
        signal_floor = float(np.mean([e.root_signal for e in self._window]))
        return move_threshold, signal_floor

    @staticmethod
    def value_band(signal_floor: float) -> tuple[float, float]:
        """The value interval whose p(1-p) is at least ``signal_floor``."""
        root = float(np.sqrt(max(1.0 - 4.0 * signal_floor, 0.0)))
        return (1.0 - root) / 2.0, (1.0 + root) / 2.0

    # -- screening --------------------------------------------------------------------------------------------
    def screen(self, rollout: RolloutTurns) -> Optional[BranchPoint]:
        """Screen one normal rollout with the thresholds of the window before it, then add it to the window.

        Updates the task's pending entry: a selected turn replaces it, a rollout without one clears it, so a pending
        entry always comes from the task's most recent normal rollout.
        """
        turns = int(len(rollout.first))
        moves = np.asarray(rollout.last, dtype=np.float64) - np.asarray(rollout.first, dtype=np.float64)
        candidates = np.arange(1, max(turns - 1, 1))  # not the root turn, not the last turn
        candidates = candidates[(candidates / max(turns, 1)) <= self.config.max_position] if turns > 2 else candidates[:0]
        thresholds = self.thresholds()
        point: Optional[BranchPoint] = None
        reason = "selected"
        if thresholds is None:
            reason = "window_warming_up"
        elif turns < 4 or candidates.size == 0:
            reason = "too_short"
        elif self.config.skip_subagent_or_compaction and rollout.has_subagent_or_compaction:
            reason = "subagent_or_compaction"
        elif self.config.source == "solved" and not rollout.solved:
            reason = "not_solved"
        else:
            move_threshold, signal_floor = thresholds
            low, high = self.value_band(signal_floor)
            # Only moves in the direction of the outcome: a rise in a solved rollout, a drop in an unsolved one.
            toward = moves[candidates] > 0 if rollout.solved else moves[candidates] < 0
            big = candidates[(np.abs(moves[candidates]) >= move_threshold) & toward]
            if big.size == 0:
                reason = "no_large_move"
            else:
                value_before = np.asarray(rollout.last, dtype=np.float64)[big - 1]
                # One-sided band: a rise may start anywhere up to the upper edge, a drop anywhere down to the lower edge.
                informative = value_before <= high if rollout.solved else value_before >= low
                if not informative.any():
                    reason = "value_outside_band"
                else:
                    big, value_before = big[informative], value_before[informative]
                    j = int(np.argmax(np.abs(moves[big])))
                    k = int(big[j])
                    point = BranchPoint(
                        task=rollout.task,
                        rollout_id=rollout.rollout_id,
                        step=int(rollout.step),
                        solved=bool(rollout.solved),
                        turns=turns,
                        branch_turn=k,
                        value_before=float(value_before[j]),
                        move=float(moves[k]),
                        position=k / turns,
                        truncated=bool(rollout.truncated),
                    )
        self._step_screened += 1
        self._step_reasons[reason] += 1
        if point is not None:
            self.pending[rollout.task] = point
            self._step_selected.append(point)
        else:
            self.pending.pop(rollout.task, None)
        self._window.append(
            _WindowEntry(moves=np.abs(moves[candidates]) if candidates.size else np.zeros(0), root_signal=_signal(rollout.root_mean))
        )
        return point

    def take(self, task: str) -> Optional[BranchPoint]:
        """The pending branch point of ``task`` for its next dispatch; it is consumed."""
        return self.pending.pop(task, None)

    # -- monitoring -------------------------------------------------------------------------------------------
    def step_metrics(self) -> dict[str, float]:
        """Metrics of the rollouts screened since the last call; resets the per-step counters."""
        metrics: dict[str, float] = {
            "branch/screened_rollouts": float(self._step_screened),
            "branch/window_rollouts": float(len(self._window)),
            "branch/pending_tasks": float(len(self.pending)),
        }
        thresholds = self.thresholds()
        if thresholds is not None:
            move_threshold, signal_floor = thresholds
            low, high = self.value_band(signal_floor)
            metrics.update(
                {
                    "branch/move_threshold": move_threshold,
                    "branch/signal_floor": signal_floor,
                    "branch/value_band_low": low,
                    "branch/value_band_high": high,
                }
            )
        n = max(self._step_screened, 1)
        for reason in (
            "selected",
            "no_large_move",
            "value_outside_band",
            "subagent_or_compaction",
            "not_solved",
            "too_short",
            "window_warming_up",
        ):
            metrics[f"branch/rate/{reason}"] = self._step_reasons.get(reason, 0) / n
        sel = self._step_selected
        if sel:
            metrics.update(
                {
                    "branch/selected/position_mean": float(np.mean([p.position for p in sel])),
                    "branch/selected/value_before_mean": float(np.mean([p.value_before for p in sel])),
                    "branch/selected/value_before_min": float(np.min([p.value_before for p in sel])),
                    "branch/selected/value_before_max": float(np.max([p.value_before for p in sel])),
                    "branch/selected/abs_move_mean": float(np.mean([abs(p.move) for p in sel])),
                    "branch/selected/rise_fraction": float(np.mean([p.move > 0 for p in sel])),
                    "branch/selected/solved_fraction": float(np.mean([p.solved for p in sel])),
                    "branch/selected/truncated_fraction": float(np.mean([p.truncated for p in sel])),
                    "branch/selected/branch_turn_mean": float(np.mean([p.branch_turn for p in sel])),
                    "branch/selected/turns_mean": float(np.mean([p.turns for p in sel])),
                }
            )
        self._step_reasons = Counter()
        self._step_selected = []
        self._step_screened = 0
        return metrics

    # -- persistence (saved with each checkpoint) ----------------------------------------------------------------
    def state_dict(self) -> dict[str, Any]:
        return {
            "version": 1,
            "config": asdict(self.config),
            "window": [{"moves": e.moves.tolist(), "root_signal": e.root_signal} for e in self._window],
            "pending": {task: asdict(p) for task, p in self.pending.items()},
        }

    def load_state_dict(self, state: dict[str, Any]) -> None:
        if state.get("version") != 1:
            raise ValueError(f"unsupported branch replay state version {state.get('version')!r}")
        self._window.clear()
        for e in state["window"][-self.config.window_rollouts :]:
            self._window.append(_WindowEntry(moves=np.asarray(e["moves"], dtype=np.float64), root_signal=float(e["root_signal"])))
        self.pending = {task: BranchPoint(**p) for task, p in state["pending"].items()}

    def save(self, path: str) -> None:
        tmp = f"{path}.tmp"
        with open(tmp, "w") as f:
            json.dump(self.state_dict(), f)
        os.replace(tmp, path)

    def load(self, path: str) -> None:
        with open(path) as f:
            self.load_state_dict(json.load(f))


def replay_calibration_metrics(value_before: list[float], rewards: list[float]) -> dict[str, float]:
    """Health of the replays trained in a step: do they succeed as often as the critic said at the branch point?"""
    if not rewards:
        return {"branch/replay/rollouts": 0.0}
    v = np.clip(np.asarray(value_before, dtype=np.float64), 0.0, 1.0)
    r = np.asarray(rewards, dtype=np.float64)
    return {
        "branch/replay/rollouts": float(len(r)),
        "branch/replay/reward_mean": float(r.mean()),
        "branch/replay/value_before_mean": float(v.mean()),
        "branch/replay/reward_minus_value": float(r.mean() - v.mean()),
        "branch/replay/outcome_variance_vs_predicted": float(r.var() / max(float(np.mean(v * (1 - v))), 1e-6)),
    }


# ---------------------------------------------------------------------------------------------------------------
# Runtime shared by the dispatcher (RolloutManager) and the training step (SingleController diagnostics).
#
# Files, under ``replay_dir`` (the directory the Gym model server reads through NEMO_GYM_BRANCH_REPLAY_DIR):
#   <rollout_id>.calls.jsonl   written by the model server: every chat completion of a rollout
#   <rollout_id>.plan.json     written here at dispatch: {"source_rollout_id", "branch_turn"}
#   <rollout_id>.replay.jsonl  written by the model server: one line per replayed call, with context_match
# A rollout id is the canonical TQ sample id of its root row, which is also Gym's capture key.
# ---------------------------------------------------------------------------------------------------------------

import threading  # noqa: E402
from pathlib import Path  # noqa: E402

REPLAY_DIR_ENV = "NEMO_GYM_BRANCH_REPLAY_DIR"
STATE_FILENAME = "branch_replay_state.json"


def turn_runs(mask_row: np.ndarray) -> list[tuple[int, int]]:
    """[start, end) of every run of generated tokens in a row's token mask: one run per turn."""
    m = np.asarray(mask_row) > 0
    if not m.any():
        return []
    d = np.diff(np.concatenate([[0], m.astype(np.int8), [0]]))
    return list(zip(np.flatnonzero(d == 1).tolist(), np.flatnonzero(d == -1).tolist()))


_ATTEMPT_SUFFIX = re.compile(r"_a[0-9a-f]{32}$")


def training_row_id(gym_rollout_id: str) -> str:
    """``{group}_g{i}_a{attempt uuid}`` -> ``{group}_g{i}``; an id without the attempt suffix is returned as is."""
    return _ATTEMPT_SUFFIX.sub("", gym_rollout_id)


class BranchReplayRuntime:
    def __init__(self, config: BranchReplayConfig, replay_dir: str):
        self.config = config
        self.dir = Path(replay_dir)
        self.dir.mkdir(parents=True, exist_ok=True)
        self.selector = BranchSelector(config)
        # A rollout has two ids.  Gym knows it by the id of its current attempt, ``{group}_g{i}_a{attempt uuid}``:
        # the model server names the recording, plan and replay log after it.  The training step knows it by the
        # training row id ``{group}_g{i}``.  Dispatch records the attempt id of every rollout; the training step
        # looks the files up through it and uses it as the source id of a branch point.
        self._gym_id: dict[str, str] = {}
        # Replay rollouts dispatched and not yet trained: training row id -> the branch point they restart from.
        self.in_flight: dict[str, BranchPoint] = {}
        self._lock = threading.Lock()
        self._dispatch = Counter()

    # -- files ------------------------------------------------------------------------------------------------
    def _calls(self, rollout_id: str) -> Path:
        return self.dir / f"{rollout_id}.calls.jsonl"

    def _plan(self, rollout_id: str) -> Path:
        return self.dir / f"{rollout_id}.plan.json"

    def _replay_log(self, rollout_id: str) -> Path:
        return self.dir / f"{rollout_id}.replay.jsonl"

    @staticmethod
    def _remove(path: Path) -> None:
        try:
            path.unlink()
        except FileNotFoundError:
            pass
        except OSError:
            pass

    def _remove_rollout_files(self, gym_id: str) -> None:
        for path in (self._plan(gym_id), self._replay_log(gym_id), self._calls(gym_id)):
            self._remove(path)

    def _recorded_calls(self, rollout_id: str) -> Optional[set[int]]:
        try:
            with open(self._calls(rollout_id), encoding="utf-8") as f:
                return {int(json.loads(line)["call"]) for line in f if line.strip()}
        except (OSError, ValueError, KeyError):
            return None

    # -- dispatch ---------------------------------------------------------------------------------------------
    def on_dispatch(self, task: Optional[str], rollout_id: str, sample: Any) -> Optional[BranchPoint]:
        """Called when a rollout of ``task`` is about to be sent to Gym under ``rollout_id``.

        Takes the task's pending branch point, if any, and turns this rollout into a replay by writing its plan.
        The point is remembered on ``sample`` so that a re-dispatch of the same sample replays the same point.
        """
        row_id = training_row_id(rollout_id)
        with self._lock:
            # A retry of the same rollout runs under a new attempt id: drop what the previous attempt left.
            previous_id = self._gym_id.get(row_id)
            if previous_id is not None and previous_id != rollout_id:
                self._remove_rollout_files(previous_id)
            self._gym_id[row_id] = rollout_id
            self.in_flight.pop(row_id, None)
            if not task:
                return None
            point: Optional[BranchPoint] = None
            remembered = sample.get("_branch_point") if isinstance(sample, dict) else None
            if isinstance(remembered, BranchPoint):
                point = remembered
            else:
                point = self.selector.take(task)
            if point is None:
                self._dispatch["normal"] += 1
                return None
            calls = self._recorded_calls(point.rollout_id)
            if calls is None:
                self._dispatch["source_recording_missing"] += 1
                return None
            if not set(range(point.branch_turn)) <= calls or len(calls) != point.turns:
                # The recorded calls do not line up with the turns the critic scored (a retried or lost call).
                self._dispatch["source_recording_misaligned"] += 1
                self._remove(self._calls(point.rollout_id))
                return None
            tmp = self._plan(rollout_id).with_suffix(".tmp")
            tmp.write_text(json.dumps({"source_rollout_id": point.rollout_id, "branch_turn": point.branch_turn}))
            os.replace(tmp, self._plan(rollout_id))
            if isinstance(sample, dict):
                sample["_branch_point"] = point
            self.in_flight[row_id] = point
            self._dispatch["replay"] += 1
            return point

    # -- training step ----------------------------------------------------------------------------------------
    def observe_step(
        self,
        *,
        step: int,
        sample_ids: list[str],
        debug_rows: list[dict],
        rewards: np.ndarray,
        trained: np.ndarray,
        token_mask: np.ndarray,
        values: np.ndarray,
        truncated: Optional[np.ndarray] = None,
    ) -> dict[str, float]:
        """Screen the normal rollouts of a trained batch and account for its replay rollouts; return the metrics."""
        replay_values: list[float] = []
        replay_rewards: list[float] = []
        replay_matches: list[float] = []
        replay_generated_turns: list[int] = []
        with self._lock:
            for i, sample_id in enumerate(sample_ids):
                row = debug_rows[i] if i < len(debug_rows) else {}
                if int(row.get("trace_in_rollout_idx", 0)) != 0:
                    continue
                gym_id = self._gym_id.pop(sample_id, sample_id)
                if bool(row.get("is_empty_rollout", False)):
                    self.in_flight.pop(sample_id, None)
                    self._remove_rollout_files(gym_id)
                    continue
                info = row.get("rollout_info") or {}
                if isinstance(info, (list, tuple)):
                    info = info[0] if info else {}
                runs = turn_runs(token_mask[i])
                replay_point = self.in_flight.pop(sample_id, None)
                if replay_point is not None:
                    # A replay: its generated turns start at the branch turn. Not screened again.
                    if trained[i] > 0:
                        replay_values.append(replay_point.value_before)
                        replay_rewards.append(float(rewards[i] > 0.5))
                        replay_generated_turns.append(len(runs))
                    try:
                        with open(self._replay_log(gym_id), encoding="utf-8") as f:
                            entries = [json.loads(line) for line in f if line.strip()]
                        if entries:
                            replay_matches.append(float(np.mean([bool(e.get("context_match")) for e in entries])))
                    except OSError:
                        pass
                    self._remove_rollout_files(gym_id)
                    self._remove(self._calls(replay_point.rollout_id))
                    continue
                is_truncated = truncated is not None and bool(truncated[i])
                if (trained[i] <= 0 and not is_truncated) or not runs:
                    # A masked rollout is not a source and says nothing new about the task's pending point. A rollout
                    # that hit the context limit is the exception: it is screened, as an unsolved rollout.
                    self._remove(self._calls(gym_id))
                    continue
                task = str(info.get("instance_id") or "")
                first = np.array([values[i][a] for a, _ in runs], dtype=np.float64)
                last = np.array([values[i][b - 1] for _, b in runs], dtype=np.float64)
                a0, b0 = runs[0]
                previous = self.selector.pending.get(task)
                point = self.selector.screen(
                    RolloutTurns(
                        task=task,
                        rollout_id=gym_id,
                        step=int(step),
                        solved=bool(rewards[i] > 0.5) and not is_truncated,
                        first=first,
                        last=last,
                        root_mean=float(np.mean(values[i][a0:b0])),
                        has_subagent_or_compaction=bool(
                            (info.get("num_subagent_sessions") or 0) > 0 or (info.get("num_compactions") or 0) > 0
                        ),
                        truncated=is_truncated,
                    )
                )
                # Keep only the recording a pending point needs.
                if previous is not None and (point is None or previous.rollout_id != point.rollout_id):
                    self._remove(self._calls(previous.rollout_id))
                if point is None:
                    self._remove(self._calls(gym_id))
            metrics = self.selector.step_metrics()
            total = max(sum(self._dispatch.values()), 1)
            for key in ("normal", "replay", "source_recording_missing", "source_recording_misaligned"):
                metrics[f"branch/dispatch/{key}"] = float(self._dispatch.get(key, 0))
            metrics["branch/dispatch/replay_fraction"] = self._dispatch.get("replay", 0) / total
            self._dispatch = Counter()
            metrics["branch/replay/in_flight"] = float(len(self.in_flight))
        metrics.update(replay_calibration_metrics(replay_values, replay_rewards))
        if replay_matches:
            metrics["branch/replay/context_match_mean"] = float(np.mean(replay_matches))
            metrics["branch/replay/context_match_all"] = float(np.mean([m >= 1.0 for m in replay_matches]))
        if replay_generated_turns:
            metrics["branch/replay/generated_turns_mean"] = float(np.mean(replay_generated_turns))
        return metrics

    # -- checkpoint -------------------------------------------------------------------------------------------
    def save(self, directory: str) -> None:
        with self._lock:
            self.selector.save(os.path.join(directory, STATE_FILENAME))

    def load_if_present(self, directory: str) -> bool:
        path = os.path.join(directory, STATE_FILENAME)
        if not os.path.exists(path):
            return False
        with self._lock:
            self.selector.load(path)
        return True


_RUNTIME: Optional[BranchReplayRuntime] = None


def install_runtime(config: BranchReplayConfig) -> Optional[BranchReplayRuntime]:
    """Create the process-wide runtime when branch replay is enabled; requires NEMO_GYM_BRANCH_REPLAY_DIR."""
    global _RUNTIME
    if not config.enabled:
        _RUNTIME = None
        return None
    replay_dir = (config.dir or os.environ.get(REPLAY_DIR_ENV, "")).strip()
    if not replay_dir:
        raise ValueError(
            f"ppo.branch_replay.enabled needs ppo.branch_replay.dir (or {REPLAY_DIR_ENV}): a directory the Gym model "
            "server shares through its branch_replay_dir"
        )
    _RUNTIME = BranchReplayRuntime(config, replay_dir)
    return _RUNTIME


def runtime() -> Optional[BranchReplayRuntime]:
    return _RUNTIME
