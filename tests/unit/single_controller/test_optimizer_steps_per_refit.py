_GATE_CLOSED_TIMEOUT_S = 0.05


def _admit_until_gate_closes(sampler, published_version: int) -> list[int]:
    """Admit batches against a fixed published version until the gate blocks."""
    admitted: list[int] = []
    gate_open = True
    while gate_open:
        try:
            admitted.append(
                _run(
                    asyncio.wait_for(
                        sampler.admit(trainer_version_fn=lambda: published_version),
                        timeout=_GATE_CLOSED_TIMEOUT_S,
                    )
                )
            )
        except asyncio.TimeoutError:
            gate_open = False
    return admitted


class TestInOrderBurstGate:
    def test_each_refit_admits_the_next_burst(self):
        sampler = InOrderSampler(
            FakeBuffer(), max_lookahead_versions=1, optimizer_steps_per_refit=3
        )

        assert _admit_until_gate_closes(sampler, published_version=0) == [0, 1, 2, 3]
        steady_state = _admit_until_gate_closes(sampler, published_version=3)

        # Generated by version 3 and trained on at steps 4..6: staleness runs
        # from max_lookahead_versions to max_lookahead_versions + mu - 1, so its
        # mean is phi + (mu - 1) / 2 with phi = max_lookahead_versions.
        assert steady_state == [4, 5, 6]
        staleness = [target_step - 3 for target_step in steady_state]
        assert staleness == [1, 2, 3]
        assert sum(staleness) / len(staleness) == 1 + (3 - 1) / 2

    @pytest.mark.parametrize(
        ("cfg", "expected"),
        [
            # (max_lookahead_versions + mu) batches: Q_b = (phi + mu) B.
            (InOrderSamplerConfig(max_lookahead_versions=1), 4 * (1 + 3)),
            (
                InOrderSamplerConfig(
                    max_lookahead_versions=1, warmup_lookahead_versions=2
                ),
                4 * (2 + 3),
            ),
            # The staleness window already bounds the gated samplers' lookahead
            # from the published version, so mu does not widen them.
            (WeightFifoSamplerConfig(max_staleness_versions=2), 4 * (2 + 1)),
            (ReadyFirstSamplerConfig(max_staleness_versions=2), 4 * (2 + 1)),
        ],
    )
    def test_required_capacity_covers_a_burst(self, cfg, expected):
        assert (
            required_buffer_capacity_for_config(
                cfg,
                groups_per_step=4,
                min_groups_for_streaming_train=1,
                optimizer_steps_per_refit=3,
            )
            == expected
        )

    def test_instance_capacity_matches_the_config_capacity(self):
        sampler = InOrderSampler(
            FakeBuffer(), max_lookahead_versions=1, optimizer_steps_per_refit=3
        )

        assert sampler.required_buffer_capacity(groups_per_step=4) == 16


class TestValidation:
    @pytest.mark.parametrize(
        "sampler",
        [
            WindowedSamplerConfig(max_staleness_versions=1),
            WeightFifoSamplerConfig(max_staleness_versions=1),
            ReadyFirstSamplerConfig(max_staleness_versions=1),
        ],
    )
    def test_a_staleness_window_shorter_than_a_burst_is_rejected(self, sampler):
        cfg = _master_config(sampler=sampler, optimizer_steps_per_refit=3)

        with pytest.raises(ValueError, match="optimizer_steps_per_refit - 1"):
            validate_single_controller_config(cfg)

    @pytest.mark.parametrize(
        "sampler",
        [
            WindowedSamplerConfig(max_staleness_versions=2),
            WeightFifoSamplerConfig(max_staleness_versions=2),
            ReadyFirstSamplerConfig(max_staleness_versions=2),
            InOrderSamplerConfig(max_lookahead_versions=0),
        ],
    )
    def test_a_window_that_spans_the_burst_is_accepted(self, sampler):
        validate_single_controller_config(
            _master_config(sampler=sampler, optimizer_steps_per_refit=3)
        )

    def test_buffer_capacity_is_checked_against_the_burst(self):
        # 8 prompts per step x (1 lookahead + 8 steps) = 72 slots > 64 buffered.
        cfg = _master_config(
            sampler=InOrderSamplerConfig(max_lookahead_versions=1),
            optimizer_steps_per_refit=8,
            max_buffered_rollouts=64,
        )

        with pytest.raises(ValueError, match=r"required capacity \(72\)"):
            validate_single_controller_config(cfg)

    def test_colocated_generation_is_rejected(self):
        cfg = _master_config(optimizer_steps_per_refit=2)
        cfg.policy["generation"] = {
            "backend": "megatron",
            "colocated": {"enabled": True},
        }

        with pytest.raises(ValueError, match="non-colocated generation"):
            validate_single_controller_config(cfg)

    def test_ppo_is_rejected(self):
        cfg = _ppo_master_config()
        cfg.async_rl.optimizer_steps_per_refit = 2

        with pytest.raises(ValueError, match="GRPO-only"):
            validate_single_controller_config(cfg)


class _EveryStepSampler(_EmptySampler):
    """Hands the pump a full step on every select and records the versions it saw."""

    def __init__(self, ctrl_ref: list) -> None:
        self._ctrl_ref = ctrl_ref
        self.versions_at_select: list[tuple[int, int]] = []

    async def select(self, **kwargs):
        ctrl = self._ctrl_ref[0]
        self.versions_at_select.append(
            (kwargs["current_train_weight"], ctrl._published_policy_version())
        )
        meta = KVBatchMeta(
            partition_id="rollout_data",
            task_name="train",
            sample_ids=["sample-0", "sample-1"],
            fields=[],
            sequence_lengths=[1, 1],
            tags=_one_group_tags(2),
        )
        return meta, 2


def _burst_controller(monkeypatch, *, steps_per_refit: int, max_num_steps: int):
    ctrl_ref: list = []
    sampler = _EveryStepSampler(ctrl_ref)
    ctrl = _train_pump_controller(sampler=sampler)
    ctrl_ref.append(ctrl)
    ctrl._async_cfg.optimizer_steps_per_refit = steps_per_refit
    ctrl._algo_cfg.max_num_steps = max_num_steps
    # Not exhausted, so only max_num_steps is the last step and saves follow
    # save_period alone.
    ctrl._rollout_exhausted.clear()
    published: list[int] = []

    async def sync_weights(**kwargs) -> int:
        del kwargs
        published.append(ctrl._trainer_version)
        return 0

    ctrl._sync_weights = AsyncMock(side_effect=sync_weights)
    ctrl._logger = MagicMock()
    monkeypatch.setattr(single_controller.ray, "cluster_resources", lambda: {})
    return ctrl, sampler, published


class TestTrainPumpBursts:
    def test_refits_once_per_burst_while_the_version_advances_per_step(
        self, monkeypatch
    ):
        ctrl, sampler, published = _burst_controller(
            monkeypatch, steps_per_refit=3, max_num_steps=7
        )

        asyncio.run(asyncio.wait_for(ctrl._train_pump(), timeout=2.0))

        assert ctrl._trainer_version == ctrl._train_steps == 7
        assert published == [3, 6]
        assert [
            call.args[0]
            for call in ctrl._rollout_manager.set_weight_version.call_args_list
        ] == [3, 6]
        # (trainer version, published version) as each step selected its batch.
        assert sampler.versions_at_select == [
            (0, 0),
            (1, 0),
            (2, 0),
            (3, 3),
            (4, 3),
            (5, 3),
            (6, 6),
        ]
        lags = [
            call.args[0]["weight_version_lag"]
            for call in ctrl._logger.log_metrics.call_args_list
            if call.kwargs.get("prefix") == "train"
        ]
        # Every sample is tagged version 0, so the lag counts optimizer steps.
        assert lags == list(range(7))

    def test_a_checkpoint_step_ends_the_burst(self, monkeypatch):
        ctrl, sampler, published = _burst_controller(
            monkeypatch, steps_per_refit=3, max_num_steps=5
        )
        ctrl._master_config.checkpointing = {"enabled": True, "save_period": 2}
        saved_at: list[tuple[int, int]] = []

        async def save_checkpoint(metrics, **kwargs) -> None:
            del metrics, kwargs
            saved_at.append((ctrl._trainer_version, ctrl._published_policy_version()))

        ctrl._save_checkpoint = AsyncMock(side_effect=save_checkpoint)

        asyncio.run(asyncio.wait_for(ctrl._train_pump(), timeout=2.0))

        # Saves at 2, 4 and the final step 5; each one publishes first, so the
        # checkpointed weights are the ones generation serves after a resume.
        assert saved_at == [(2, 2), (4, 4), (5, 5)]
        assert published == [2, 4, 5]
        assert [version for _, version in sampler.versions_at_select] == [
            0,
            0,
            2,
            2,
            4,
        ]
